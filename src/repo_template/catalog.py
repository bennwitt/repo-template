# What Claude Code (2.1) runs when it loads a skill, found as it finds it. It drops a leading
# BOM, ends the frontmatter at the first "---" anywhere, substitutes the arguments, and prefixes
# a line, then runs fenced ```! blocks and !`command` after whitespace (JavaScript's \s) or a
# line start, once ordinary inline code spans (as in "`!` preserved") are blanked.
CLAUDE_FRONTMATTER = re.compile(r"^---\s*\n([\s\S]*?)---\s*\n?")
JS_SPACE = "\t\n\v\f\r \u00a0\u1680\u2000-\u200a\u2028\u2029\u202f\u205f\u3000\ufeff"
FENCED_COMMAND = re.compile(r"```!\s*\n?([\s\S]*?)\n?```")
INLINE_COMMAND = re.compile(rf"(?:^|(?<=[{JS_SPACE}]))!`([^`]+)`")
INLINE_CODE = re.compile(r"`[^`\n]+`")
ARGUMENT = re.compile(r"\$ARGUMENTS(?:\[\d+\])?|\$\d+")
HOOKS_KEY = re.compile(r"^[\"']?hooks[\"']?[ \t]*:", re.M)


def claude_code_view(text: str) -> tuple[str, str] | None:
    """(frontmatter, body) as Claude Code splits a SKILL.md; None if it sees no frontmatter."""
    match = CLAUDE_FRONTMATTER.match(text.removeprefix("\ufeff"))
    return (match.group(1), text.removeprefix("\ufeff")[match.end() :]) if match else None


def _commands(text: str) -> list[str]:
    commands = [match.group(1).strip() for match in FENCED_COMMAND.finditer(text)]
    if "!`" in text:

        def blank(match: re.Match[str]) -> str:
            before = text[match.start() - 1] if match.start() else ""
            span = match.group()
            return span if before in {"!", "`"} else "`" + " " * (len(span) - 2) + "`"

        blanked = INLINE_CODE.sub(blank, text)
        commands += [match.group(1).strip() for match in INLINE_COMMAND.finditer(blanked)]
    return [command for command in commands if command]


def load_commands(text: str) -> list[str]:
    """The commands a SKILL.md can run when it loads: in the file as written, in the body as
    Claude Code cuts it, and in that body with arguments that open or close inline code."""
    view = claude_code_view(text)
    body = "\n\n" + (view[1] if view else text)
    candidates = [text, body]
    if ARGUMENT.search(body):
        candidates += [ARGUMENT.sub(probe, body) for probe in ("`x`", "`")]
    found: list[str] = []
    for candidate in candidates:
        found += [command for command in _commands(candidate) if command not in found]
    return found


def runs_on_load(text: str) -> list[str]:
    """What a SKILL.md runs as it loads: its commands, and "hooks:" if it declares hooks."""
    view = claude_code_view(text)
    hooks = bool(view and HOOKS_KEY.search(view[0]))
    return load_commands(text) + (["hooks:"] if hooks else [])


def _json(root: Path, name: str) -> Any:
    path = root / name
    try:
        return json.loads(path.read_text())
    except FileNotFoundError:
        raise ValueError(f"{path} is missing") from None
    except json.JSONDecodeError as exc:
        raise ValueError(f"cannot read {path}: {exc}") from exc


def _license_file(source: str, name: str) -> str:
    return f"{LICENSES_DIR}/{source.replace('/', '_')}__{name}.txt"


def skill_folder(root: Path, name: str) -> Path:
    """Where a catalog skill lives: the folder holding its SKILL.md, under .agents/packs (pack
    skills) or .agents/skills. A folder without one (the ignored caches a moved skill leaves
    behind) counts only when neither holds a SKILL.md."""
    for folder in (PACKS_DIR, SKILLS_DIR):
        if (root / folder / name / "SKILL.md").is_file():
            return root / folder / name
    packed = root / PACKS_DIR / name
    return packed if packed.is_dir() else root / SKILLS_DIR / name


def placement(
    root: Path, names: Iterable[str], in_packs: AbstractSet[str]
) -> list[tuple[str, str]]:
    """Each skill that isn't where it belongs, with why: a skill a pack lists lives in
    .agents/packs, where Codex doesn't look on its own, and every other in .agents/skills."""
    found = []
    for name in names:
        held = [d for d in (SKILLS_DIR, PACKS_DIR) if (root / d / name / "SKILL.md").is_file()]
        wanted = PACKS_DIR if name in in_packs else SKILLS_DIR
        if len(held) > 1:
            found.append((name, f"is in both {SKILLS_DIR} and {PACKS_DIR}; keep one"))
        elif held and held[0] != wanted:
            why = "a pack lists it" if name in in_packs else "no pack lists it"
            found.append(
                (name, f"{why}, so it belongs in {wanted}: git mv {held[0]}/{name} {wanted}/{name}")
            )
    return found


def read_skill(path: Path) -> str:
    with path.open(newline="") as handle:  # the file's own line endings, as Git hashes them
        return handle.read()


def _folder(entry: dict[str, Any]) -> str:
    return str(entry.get("skillPath", "")).rsplit("/", 1)[0]


# Git tree hashing, so the committed folder can be compared with the lock without a network.


def blob_sha(data: bytes) -> str:
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()  # noqa: S324 (git's hash)


def tree_sha(entries: list[tuple[str, str, str]]) -> str:
    """A git tree object's SHA from (mode, name, sha) entries; trees sort as if named "name/"."""

    def order(entry: tuple[str, str, str]) -> bytes:
        mode, name, _ = entry
        return os.fsencode(name) + (b"/" if mode == "40000" else b"")

    body = b"".join(
        mode.encode() + b" " + os.fsencode(name) + b"\0" + bytes.fromhex(sha)
        for mode, name, sha in sorted(entries, key=order)
    )
    return hashlib.sha1(b"tree %d\0" % len(body) + body).hexdigest()  # noqa: S324


def folder_tree(files: dict[str, tuple[str, str]]) -> str:
    """The tree SHA of {relative path: (mode, blob sha)}."""

    def build(prefix: str) -> str:
        entries: list[tuple[str, str, str]] = []
        folders: set[str] = set()
        for path, (mode, sha) in files.items():
            if not path.startswith(prefix):
                continue
            rest = path[len(prefix) :]
            if "/" in rest:
                folders.add(rest.split("/", 1)[0])
            else:
                entries.append((mode, rest, sha))
        entries.extend(("40000", folder, build(f"{prefix}{folder}/")) for folder in folders)
        return tree_sha(entries)

    return build("")


def _git(root: Path, *args: str) -> bytes:
    done = subprocess.run(["git", "-C", str(root), *args], capture_output=True, check=False)
    if done.returncode:
        raise ValueError(f"git {args[0]} failed in {root}: {done.stderr.decode().strip()}")
    return done.stdout


@dataclass
class SkillFiles:
    """What Git knows about each skill folder under .agents/skills and .agents/packs."""

    files: dict[str, dict[str, tuple[str, str]]] = field(default_factory=dict)
    unusual: dict[str, list[str]] = field(default_factory=dict)  # links, submodules, escapes
    untracked: dict[str, list[str]] = field(default_factory=dict)


def _in_skill(path: str) -> tuple[str, str] | None:
    """(skill, path inside it) for .agents/{skills,packs}/<skill>/<path>."""
    parts = path.split("/")
    if len(parts) < 4 or "/".join(parts[:2]) not in {SKILLS_DIR, PACKS_DIR}:
        return None
    return parts[2], "/".join(parts[3:])


def list_skill_files(root: Path) -> SkillFiles:
    """The tracked files of every skill, hashed from the working tree (content and executable
    bit), so an uncommitted edit counts too; plus the untracked, unignored files, which are live
    through each skill's link."""
    file_mode = _git(root, "config", "--bool", "--default", "true", "core.fileMode").strip()
    listing = SkillFiles()
    tracked = _git(root, "ls-files", "-s", "-z", "--", SKILLS_DIR, PACKS_DIR)
    for record in tracked.split(b"\0"):
        meta, _, raw = record.partition(b"\t")  # the metadata never holds a tab; a path may
        found = _in_skill(os.fsdecode(raw)) if raw else None
        if found is None:
            continue
        skill, path = found
        index_mode = meta.split()[0].decode()
        folder = root / "/".join(os.fsdecode(raw).split("/")[:3])
        file = folder / path
        if (
            index_mode not in {"100644", "100755"}
            or file.is_symlink()
            or not file.resolve().is_relative_to(folder.resolve())
        ):
            listing.unusual.setdefault(skill, []).append(path)
            continue
        if not file.is_file():
            continue  # deleted in the working tree: it drops out of the hash
        mode = index_mode
        if file_mode == b"true":
            mode = "100755" if file.stat().st_mode & stat.S_IXUSR else "100644"
        listing.files.setdefault(skill, {})[path] = (mode, blob_sha(file.read_bytes()))
    untracked = _git(
        root, "ls-files", "-o", "--exclude-standard", "-z", "--", SKILLS_DIR, PACKS_DIR
    )
    for raw in filter(None, untracked.split(b"\0")):
        found = _in_skill(os.fsdecode(raw))
        if found:
            listing.untracked.setdefault(found[0], []).append(found[1])
    return listing


Completes = Callable[[str, str], bool | None]


def _completes(lock: dict[str, Any], listing: SkillFiles) -> Completes:
    def completes(name: str, text: str) -> bool | None:
        entry, files = lock.get(name), listing.files.get(name)
        if not isinstance(entry, dict) or not files or "SKILL.md" not in files:
            return None
        files = {**files, "SKILL.md": (files["SKILL.md"][0], blob_sha(text.encode()))}
        return folder_tree(files) == entry.get("skillFolderHash")

    return completes


def lock_completion(root: Path) -> Completes:
    """completes(skill, text): would the skill's folder, with this SKILL.md text, have the lock's
    tree? None when nothing can say: no lock, not in it, or no Git checkout."""
    if not (root / LOCK_NAME).is_file():
        return lambda name, text: None
    try:
        return _completes(_json(root, LOCK_NAME).get("skills", {}), list_skill_files(root))
    except (OSError, ValueError):
        return lambda name, text: None


# Overrides.


def origin(root: Path, name: str) -> str:
    """Where a vendored skill's original is, for its change note, so the note still says it
    when the folder is copied out of this repository."""
    try:
        entry = _json(root, LOCK_NAME).get("skills", {}).get(name)
        sources = _json(root, SOURCES_NAME)
    except ValueError:
        entry, sources = None, {}
    if not isinstance(entry, dict):
        return f"Upstream's text is in {OVERRIDES_NAME}."
    source = entry.get("source", "?")
    record = sources.get("skills", {}).get(name, {})
    spdx = record.get("license") or sources.get("sources", {}).get(source, {}).get("license", "?")
    url = upstream_url(source, record.get("commit", "HEAD"), _folder(entry))
    return f"Original: {url} ({spdx})."


def upstream_skill_md(text: str, record: dict[str, Any], completed: bool | None) -> str:
    """The upstream SKILL.md an overridden skill's `text` was made from. `completed` is
    lock_completion's verdict on `text` itself. Unverified text is taken as upstream only the
    first time, when nothing is recorded yet."""
    if completed:
        return text  # upstream as is: vendored again, the override not yet applied
    base, upstream = record.get("base"), record.get("upstream")
    if isinstance(base, dict) and isinstance(upstream, str):
        candidate = without_change_note(text)
        for key, raw in base.items():
            candidate = restore_field(candidate, key, raw)
        if blob_sha(candidate.encode()) == upstream:
            return candidate
    if completed is None and upstream is None and not has_change_note(text):
        return text  # nothing to check it against, and nothing recorded: take it as upstream
    raise ValueError(
        f"SKILL.md differs from upstream beyond its override; only the fields in "
        f"{OVERRIDES_NAME} may change (restore the rest, or vendor it again)"
    )


def override(
    text: str,
    fields: dict[str, str | bool],
    record: dict[str, Any],
    completed: bool | None,
    note_origin: str,
) -> tuple[str, str]:
    """(upstream SKILL.md, what the override makes of it)."""
    upstream = upstream_skill_md(text, record, completed)
    if has_change_note(upstream):
        raise ValueError("upstream's frontmatter already has a '# Changed by repo-template' line")
    for key in fields:
        if field_count(upstream, key) > 1:
            raise ValueError(f"upstream's frontmatter has {key!r} more than once")
    expected = upstream
    for key, value in fields.items():
        expected = set_field(expected, key, value)
    return upstream, with_change_note(expected, list(fields), note_origin)


# Integrity.


def _frontmatter_problem(text: str) -> str | None:
    """Why Claude Code would read the frontmatter differently from this repository, if it
    would: a BOM, spaces after a ---, or a --- inside a line."""
    try:
        ours = frontmatter_text(text)
    except ValueError as exc:
        return str(exc)
    view = claude_code_view(text)
    if view is None or view[0] != ours or text.startswith("\ufeff"):
        return (
            "Claude Code would read its frontmatter differently; keep each --- on a line of its own"
        )
    return None


def _check_license(root: Path, label: str, source: str, record: Any, problems: _Problems) -> None:
    """A license record: an SPDX id, the copyright line as stated upstream, and each license
    text, copied here and pinned to its upstream blob SHA."""
    if not isinstance(record, dict):
        problems.add(None, f"{label}: no license record in {SOURCES_NAME}")
        return
    for key in ("license", "copyright"):
        if not isinstance(record.get(key), str) or not record[key].strip():
            problems.add(None, f"{label}: no '{key}' in {SOURCES_NAME}")
    files = record.get("licenseFiles")
    if not isinstance(files, dict) or not files:
        problems.add(
            None,
            f"{label}: no 'licenseFiles' (upstream file name → its blob SHA) in {SOURCES_NAME}",
        )
        return
    for name, sha in files.items():
        path = root / _license_file(source, name)
        if not path.is_file():
            problems.add(None, f"{label}: license text {_license_file(source, name)} is missing")
        elif sha != blob_sha(path.read_bytes()):
            problems.add(
                None,
                f"{label}: {_license_file(source, name)} isn't the upstream text recorded in "
                f"{SOURCES_NAME}; copy it again",
            )


@dataclass
class _Problems:
    errors: list[str] = field(default_factory=list)
    skills: set[str] = field(default_factory=set)  # skills with a problem: not linked

    def add(self, skill: str | None, message: str) -> None:
        self.errors.append(f"{skill}: {message}" if skill else message)
        if skill:
            self.skills.add(skill)


def _license_files(skill_dir: Path) -> list[str]:
    return sorted(
        path.name
        for path in skill_dir.iterdir()
        if path.is_file() and LICENSE_FILE.fullmatch(path.name)
    )


def own_license(skill_dir: Path, text: str, source_license: str) -> list[str]:
    """Why a vendored skill may carry a license of its own: license files, or a frontmatter
    `license` field that isn't its source's."""
    found = _license_files(skill_dir)
    try:
        stated = read_fields(text).get("license", "")
    except ValueError:
        stated = ""
    differs = stated and stated.strip().casefold() != source_license.strip().casefold()
    return found + ([f"license: {stated}"] if differs else [])


def integrity(
    root: Path,
    names: list[str],
    rewriting: AbstractSet[str] = frozenset(),
) -> tuple[list[str], set[str]]:
    """Every problem with the catalog's provenance, as error lines, and the skills they make
    unsafe to link. `rewriting` names overridden skills `globals --check` plans to rewrite, so
    their SKILL.md isn't held to the override yet."""
    problems = _Problems()
    loaded = []
    for name in (LOCK_NAME, SOURCES_NAME):
        try:
            loaded.append(_json(root, name))
        except ValueError as exc:
            problems.add(None, str(exc))
    if problems.errors:
        return problems.errors, set()  # unverifiable is reported, not treated as unsafe
    lock, sources = loaded[0].get("skills", {}), loaded[1]
    try:
        overrides = _json(root, OVERRIDES_NAME) if (root / OVERRIDES_NAME).is_file() else {}
    except ValueError as exc:
        return [str(exc)], set()
    local = sources.get("local", {})
    licensed = sources.get("sources", {})
    vendored = sources.get("skills", {})
    allowed_commands = sources.get("allowCommands", {})

    try:
        packs = _json(root, PACKS_NAME) if (root / PACKS_NAME).is_file() else {}
    except ValueError as exc:
        return [str(exc)], set()
    in_packs = {
        skill
        for pack in packs.values()
        if isinstance(pack, dict)
        for skill in pack.get("skills", [])
        if isinstance(skill, str)
    }
    for name, why in placement(root, names, in_packs):
        problems.add(name, why)
    for name in names:
        if skill_folder(root, name).is_symlink():
            problems.add(name, "its folder is a symlink; a skill is a folder in this repository")
        if name in lock and name in local:
            problems.add(name, "recorded both in the lock and as a local skill")
        elif name not in lock and name not in local:
            problems.add(
                name, f"unrecorded skill; vendor it, or add it to 'local' in {SOURCES_NAME}"
            )
    for name in sorted(set(lock) - set(names)):
        if skill_folder(root, name).is_dir():
            problems.add(name, "its folder has no SKILL.md")
        elif any(root.glob(f"{STAGE_PREFIX}*")):
            problems.add(
                name,
                "has no folder: an interrupted `globals --upgrade` holds it; run "
                "`repo-template globals --upgrade` to put it back",
            )
        else:
            problems.add(name, f"in {LOCK_NAME} but has no folder; remove the lock entry")
    for name in sorted(set(local) - set(names)):
        problems.add(name, f"in 'local' in {SOURCES_NAME} but has no folder")
    for name in sorted(set(vendored) - set(lock)):
        problems.add(None, f"{name}: under 'skills' in {SOURCES_NAME} but not vendored; remove it")
    for source, skipped in sources.get("ignored", {}).items():
        for name in sorted(set(skipped) & (set(lock) | set(names))):
            problems.add(name, f"in the catalog but listed under 'ignored' for {source}")
    for name in sorted(set(allowed_commands) - set(names)):
        problems.add(
            None, f"{name}: under 'allowCommands' in {SOURCES_NAME} but not in the catalog"
        )
    for name in sorted(set(overrides) - set(lock)):
        if name in names:
            problems.add(name, "has an override but isn't vendored; edit a local skill directly")
        else:
            problems.add(
                None, f"{name}: not in the catalog; remove its entry from {OVERRIDES_NAME}"
            )

    own: dict[str, list[str]] = {}
    for name in sorted(set(lock) & set(names)):
        skill_dir = skill_folder(root, name)
        spdx = licensed.get(lock[name].get("source"), {})
        spdx = spdx.get("license", "") if isinstance(spdx, dict) else ""
        own[name] = own_license(skill_dir, read_skill(skill_dir / "SKILL.md"), str(spdx))
    for source in sorted(licensed):
        record = licensed[source]
        users = [name for name in own if lock[name].get("source") == source]
        own_licenses = bool(users) and all(vendored.get(n, {}).get("license") for n in users)
        if own_licenses and isinstance(record, dict) and not record.get("licenseFiles"):
            continue  # every skill from it states its own license (as in anthropics/skills)
        _check_license(root, f"source {source}", source, record, problems)
    for name in sorted(own):
        entry, record = lock[name], vendored.get(name, {})
        if entry.get("source") not in licensed:
            problems.add(
                name, f"source {entry.get('source')} has no license record in {SOURCES_NAME}"
            )
        if not isinstance(record.get("commit"), str) or not SHA.fullmatch(record["commit"]):
            problems.add(name, f"no upstream 'commit' under 'skills' in {SOURCES_NAME}")
        elif record.get("tree") != entry.get("skillFolderHash"):
            problems.add(
                name,
                f"its recorded commit is for tree {str(record.get('tree'))[:12]}, not the lock's "
                f"{str(entry.get('skillFolderHash'))[:12]}; record the commit you vendored "
                f"('commit' and 'tree' under 'skills' in {SOURCES_NAME})",
            )
        allowance = record.get("allowFindings")
        if allowance is not None and not (
            isinstance(allowance, dict)
            and isinstance(allowance.get("reason"), str)
            and allowance["reason"].strip()
            and isinstance(allowance.get("counts"), dict)
            and all(isinstance(count, int) for count in allowance["counts"].values())
        ):
            problems.add(
                None, f"{name}: 'allowFindings' needs a 'reason' and the 'counts' it allows"
            )
        if own[name] and not record.get("license"):
            problems.add(
                name,
                f"carries its own license ({', '.join(own[name])}); record it as 'license' "
                f"and 'copyright' under 'skills' in {SOURCES_NAME}",
            )
    for name in sorted(set(local) & set(names)):
        record = local[name]
        if not isinstance(record, dict) or not record.get("license"):
            problems.add(name, f"local skill without a license in {SOURCES_NAME}")
            continue
        derived = record.get("derivedFrom")
        if derived is not None:
            source = derived.get("source", "?") if isinstance(derived, dict) else "?"
            _check_license(root, f"{name} (derived from {source})", source, derived, problems)
            if not isinstance(derived, dict) or not SHA.fullmatch(str(derived.get("commit"))):
                problems.add(name, "'derivedFrom' needs the upstream 'commit' it was made from")

    for name in names:
        text = read_skill(skill_folder(root, name) / "SKILL.md")
        problem = _frontmatter_problem(text)
        if problem:
            problems.add(name, problem)
        if name in allowed_commands:
            continue
        found = runs_on_load(text)
        if found:
            shown = " ".join(found[0].split())[:60]
            problems.add(
                name,
                f"SKILL.md runs commands when it loads ({shown}); review it and allow it under "
                f"'allowCommands' in {SOURCES_NAME}",
            )

    _check_mcp(root, problems)
    for leftover in sorted(root.glob(f"{STAGE_PREFIX}*")):
        problems.add(
            None,
            f"{leftover.name}: an interrupted `globals --upgrade` left it; run "
            f"`repo-template globals --upgrade` to restore or clear it",
        )
    try:
        listing = list_skill_files(root)
    except (OSError, ValueError) as exc:
        problems.add(None, f"checking vendored skills needs a Git checkout of {root}: {exc}")
        return problems.errors, problems.skills
    completes = _completes(lock, listing)
    for name in sorted(set(lock) & set(names)):
        entry = lock[name]
        for path in listing.unusual.get(name, []):
            problems.add(name, f"{path} is a symlink, a submodule or reaches outside the skill")
        for path in listing.untracked.get(name, []):
            problems.add(
                name,
                f"untracked {path} is live through the skill's link; `git add` it if it is "
                f"part of the vendored skill, else delete it",
            )
        files = dict(listing.files.get(name, {}))
        if name in overrides and "SKILL.md" in files:
            text = read_skill(skill_folder(root, name) / "SKILL.md")
            done = completes(name, text)
            fields = overrides[name].get("frontmatter", {})
            try:
                upstream, expected = override(
                    text, fields, overrides[name], done, origin(root, name)
                )
            except ValueError as exc:
                problems.add(name, str(exc))
                continue
            if not done and text != expected and name not in rewriting:
                problems.add(
                    name,
                    "SKILL.md isn't what its override makes of upstream; `repo-template "
                    "globals` rewrites it (if you didn't change the override, look first)",
                )
            files["SKILL.md"] = (files["SKILL.md"][0], blob_sha(upstream.encode()))
        if folder_tree(files) != entry.get("skillFolderHash"):
            problems.add(
                name,
                f"differs from {entry.get('source')} as vendored; restore the upstream files, "
                f"vendor it again, or make the change an override",
            )
    return problems.errors, problems.skills


def _check_mcp(root: Path, problems: _Problems) -> None:
    """The MCP catalog loads, packs use only pack servers, and every server's denied tools are
    denied for Claude Code too (Codex gets them as disabled_tools)."""
    from repo_template.mcp import cooldown_problem, deny_rules, load_mcp_servers, pack_servers

    try:
        servers = load_mcp_servers(root / ".agents")
        pack_servers(root / ".agents", servers)
    except ValueError as exc:
        problems.add(None, str(exc))
        return
    settings = root / ".agents/claude-settings.json"
    try:
        portable = (
            json.loads(settings.read_text()).get("portable", {}) if settings.is_file() else {}
        )
    except json.JSONDecodeError:
        return  # the settings merge reports it
    now = datetime.now(UTC)
    for _name, server in sorted(servers.items()):
        problem = cooldown_problem(server, now)
        if problem:
            problems.add(None, problem)
    denied = set(portable.get("permissions", {}).get("deny", []))
    for rule in sorted(deny_rules(servers) - denied):
        problems.add(
            None,
            f"{rule}: an MCP server denies this tool; add the rule to portable permissions.deny "
            f"in .agents/claude-settings.json so Claude Code denies it too",
        )


def check_integrity(root: Path, names: list[str]) -> list[str]:
    """Every problem with the catalog's provenance, as error lines."""
    return integrity(root, names)[0]


# Generated documents.


def _cell(text: str) -> str:
    """Text safe inside a Markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def _where(name: str, packs: dict[str, list[str]]) -> str:
    member = [pack for pack, skills in sorted(packs.items()) if name in skills]
    return ", ".join(f"pack `{pack}`" for pack in member) if member else "global"


def upstream_url(source: str, commit: str, path: str) -> str:
    return f"https://github.com/{source}/tree/{commit}/{path}"


def render_catalog(root: Path, names: list[str], packs: dict[str, list[str]]) -> str:
    lock = _json(root, LOCK_NAME).get("skills", {})
    sources = _json(root, SOURCES_NAME)
    overrides = _json(root, OVERRIDES_NAME) if (root / OVERRIDES_NAME).is_file() else {}
    pack_info = _json(root, PACKS_NAME) if (root / PACKS_NAME).is_file() else {}
    lines = [
        "| Pack | What it's for | Skills |",
        "| --- | --- | --- |",
        *(
            f"| `{pack}` | {_cell(pack_info.get(pack, {}).get('description', ''))} | "
            + ", ".join(f"`{skill}`" for skill in sorted(skills))
            + " |"
            for pack, skills in sorted(packs.items())
        ),
        "",
        "| Skill | Where | Source | License | Notes |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in names:
        notes = []
        if name in lock:
            entry = lock[name]
            source = entry["source"]
            record = sources.get("skills", {}).get(name, {})
            url = upstream_url(source, record.get("commit", "HEAD"), _folder(entry))
            link = f"[{source}]({url})"
            license_id = record.get("license") or sources["sources"].get(source, {}).get(
                "license", "?"
            )
            if name in overrides:
                notes.append(", ".join(overrides[name].get("frontmatter", {})) + " overridden")
        else:
            record = sources.get("local", {}).get(name, {})
            link, license_id = "this repository", record.get("license", "?")
            derived = record.get("derivedFrom")
            if derived:
                url = upstream_url(derived["source"], derived["commit"], derived["path"])
                notes.append(f"derived from [{derived['source']}]({url})")
        fields = read_fields((skill_folder(root, name) / "SKILL.md").read_text())
        fields.update(  # what `globals` writes, so --check plans what it would do
            (key, format_value(value).strip('"'))
            for key, value in overrides.get(name, {}).get("frontmatter", {}).items()
        )
        if fields.get("disable-model-invocation") == "true":
            notes.append("runs only as `/" + name + "`")
        lines.append(
            f"| `{name}` | {_where(name, packs)} | {link} | {license_id} | {'; '.join(notes)} |"
        )
    return "\n".join(lines + _mcp_rows(root))


def _mcp_rows(root: Path) -> list[str]:
    """The MCP servers table: where each runs, for which clients, what it runs, what's denied."""
    from repo_template.mcp import load_mcp_servers, pack_servers

    servers = load_mcp_servers(root / ".agents")
    if not servers:
        return []
    users: dict[str, list[str]] = {}
    for pack, refs in pack_servers(root / ".agents", servers).items():
        for name, _ in refs:
            users.setdefault(name, []).append(pack)
    rows = [
        "",
        "| MCP server | Where | Clients | Runs | Denied tools | Why |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for name, server in sorted(servers.items()):
        if server.scope == "global":
            where = "global"
        else:
            where = ", ".join(f"pack `{pack}`" for pack in sorted(users.get(name, []))) or "unused"
        if server.url:
            runs = server.url
        elif server.pin:
            runs = f"`{server.command} {server.pin.package}@{server.pin.version}`"
        else:
            runs = f"`{server.command}`"
        denied = ", ".join(f"`{tool}`" for tool in server.deny)
        clients = ", ".join(sorted(server.clients))
        rows.append(f"| `{name}` | {where} | {clients} | {runs} | {denied} | {_cell(server.why)} |")
    return rows


def _license_text(path: Path, heading: str) -> list[str]:
    if not path.is_file():
        raise ValueError(f"license text {path} is missing")
    return ["", f"### {heading}", "", "```text", path.read_text().rstrip(), "```"]


def render_notices(root: Path, names: list[str]) -> str:
    lock = _json(root, LOCK_NAME).get("skills", {})
    sources = _json(root, SOURCES_NAME)
    overrides = _json(root, OVERRIDES_NAME) if (root / OVERRIDES_NAME).is_file() else {}
    vendored = sources.get("skills", {})
    by_source: dict[str, list[str]] = {}
    for name in names:
        if name in lock:
            by_source.setdefault(lock[name]["source"], []).append(name)
    parts = [
        "# Third-party notices",
        "",
        "repo-template vendors agent skills from the projects below, under their licenses. "
        "Generated by `repo-template globals` from `.agents/.skill-lock.json`, "
        "`.agents/skill-sources.json` and `.agents/skill-overrides.json`; don't edit it by hand.",
        "",
        "Each vendored skill is the upstream folder recorded at the commit shown; "
        "`repo-template globals --check` verifies the folder against the lock. Where "
        "`.agents/skill-overrides.json` changes a skill's frontmatter, that is a modification of "
        "the original work, marked in the SKILL.md itself; the rest of the folder is unmodified. "
        "A skill's entry in `.agents/skill-overrides.json`, and the SKILL.md it produces, are "
        "under that skill's license.",
    ]
    entries: list[tuple[str, dict[str, Any], list[str], list[str]]] = []
    for source, skills in sorted(by_source.items()):
        listed, texts = [], []
        for name in skills:
            folder = _folder(lock[name])
            record = vendored.get(name, {})
            commit = record.get("commit", "HEAD")
            line = f"`{name}`: [{folder}]({upstream_url(source, commit, folder)}) at {commit[:12]}"
            if name in overrides:
                line += ", " + ", ".join(overrides[name].get("frontmatter", {})) + " modified"
            if record.get("author"):
                line += f", by {record['author']}"
            if record.get("license"):
                line += f"; under its own license, {record['license']}"
                if record.get("copyright"):
                    line += f" ({record['copyright']})"
                for file in _license_files(skill_folder(root, name)):
                    texts += _license_text(skill_folder(root, name) / file, f"{name}/{file}")
            listed.append(line)
        entries.append((source, sources["sources"].get(source, {}), listed, texts))
    for name, record in sorted(sources.get("local", {}).items()):
        derived = record.get("derivedFrom") if name in names else None
        if derived:
            url = upstream_url(derived["source"], derived["commit"], derived["path"])
            listed = [
                f"`{name}` (a derived work, under {record.get('license', '?')}): from "
                f"[{derived['path']}]({url}) at {derived['commit'][:12]}"
            ]
            entries.append((derived["source"], derived, listed, []))
    for source, record, listed, texts in entries:
        parts += ["", f"## {source}", "", f"- Source: https://github.com/{source}"]
        if record.get("license"):
            parts += [
                f"- License: {record['license']}",
                f"- Copyright: {record.get('copyright', '?')}",
            ]
        if str(record.get("license", "")).startswith("CC-BY-SA"):
            parts.append(
                f"- Changes this repository makes to these skills are licensed under "
                f"{record['license']}."
            )
        parts += ["- Skills:", *(f"  - {line}" for line in listed)]
        for file in record.get("licenseFiles", {}):
            parts += _license_text(root / _license_file(source, file), file)
        parts += texts
    return "\n".join(parts) + "\n"


def _single_block(text: str) -> bool:
    if text.count(README_START) != 1 or text.count(README_END) != 1:
        return False
    return text.index(README_START) < text.index(README_END)


def sync_documents(
    root: Path, names: list[str], packs: dict[str, list[str]], result: Result, *, check: bool
) -> None:
    """Keep the README catalog block and THIRD_PARTY_NOTICES.md in step with the catalog."""
    readme = root / "README.md"
    if readme.is_file():
        text = readme.read_text()
        if not _single_block(text):
            result.errors.append(
                f"{readme} needs exactly one catalog block, from {README_START} to {README_END}"
            )
        else:
            block = render_catalog(root, names, packs)
            updated = merge_marked_block(text, block, README_START, README_END)
            if updated == text:
                result.unchanged.append(str(readme))
            else:
                result.updated.append(f"{readme} (catalog block)")
                if not check:
                    write_file(root, "README.md", updated)
    notices = root / NOTICES_NAME
    rendered = render_notices(root, names)
    current = notices.read_text() if notices.is_file() else None
    if current == rendered:
        result.unchanged.append(str(notices))
        return
    (result.updated if current is not None else result.created).append(str(notices))
    if not check:
        write_file(root, NOTICES_NAME, rendered)
