"""The skill catalog's provenance, all offline: integrity against the lock, a license for every
skill, and the generated README catalog block and THIRD_PARTY_NOTICES.md.

A vendored skill must be byte for byte what it was vendored from: its files hash to the lock's
`skillFolderHash`, the GitHub tree SHA of the upstream folder, recorded with the commit it came
from in `.agents/skill-sources.json`. The one sanctioned difference is a frontmatter override
(`.agents/skill-overrides.json`). Its entry records the upstream text of each field it replaces
(`base`) and the upstream SKILL.md's blob SHA (`upstream`): the upstream file is rebuilt from the
local one, so the whole folder is checked, and the local file must be exactly what the override
makes of it.
"""

